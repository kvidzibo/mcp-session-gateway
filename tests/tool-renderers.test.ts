import assert from 'node:assert/strict';
import test from 'node:test';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { stripVTControlCharacters } from 'node:util';
import { visibleWidth } from '@earendil-works/pi-tui';
import { initTheme } from '@earendil-works/pi-coding-agent';

test('gateway_call native rendering retains raw details and bounds compact terminal rows', async () => {
  const root = process.cwd();
  const { loadExtensions } = await import(pathToFileURL(path.join(root, 'node_modules/@earendil-works/pi-coding-agent/dist/core/extensions/loader.js')).href);
  const { theme } = await import(pathToFileURL(path.join(root, 'node_modules/@earendil-works/pi-coding-agent/dist/modes/interactive/theme/theme.js')).href);
  initTheme('dark', false);
  const loaded = await loadExtensions([path.join(root, 'pi/runtime.ts')], root);
  assert.deepEqual(loaded.errors, []);
  const tool = loaded.extensions[0].tools.get('gateway_call').definition;
  assert.equal(loaded.extensions[0].tools.get('gateway_tools').definition.renderResult, undefined);
  const context = { args: { name: 'svc__read', arguments: { path: '界🙂'.repeat(25) } }, expanded: false, isPartial: false, executionStarted: true, argsComplete: true, showImages: false, isError: false, durationMs: 42 };
  const render = (text: string, expanded = false, width = 40, extra = {}, images = false) => {
    const component = tool.renderResult({ content: [{ type: 'text', text }, ...(images ? [{ type: 'image', mimeType: 'image/png', data: 'NEVER_DUMP_BASE64' }] : [])] }, { expanded, isPartial: false, ...extra }, theme, { ...context, expanded, ...extra });
    const lines: string[] = component.render(width);
    assert.ok(lines.every((line) => visibleWidth(line) <= width), `width ${width}`);
    if (!expanded) assert.ok(lines.length <= 13);
    component.invalidate();
    return lines.map((line) => stripVTControlCharacters(line).trimEnd()).join('\n');
  };
  const call = tool.renderCall(context.args, theme, context);
  assert.match(stripVTControlCharacters(call.render(40).join('\n')), /svc › read/);
  assert.ok(call.render(8).every((line: string) => visibleWidth(line) <= 8));
  const restored = tool.renderCall(context.args, theme, { ...context, executionStarted: false, argsComplete: false });
  assert.ok(!stripVTControlCharacters(restored.render(40).join('\n')).includes('Receiving arguments'));
  assert.match(render('{"ok":true,"nested":{"n":2}}', true), /"nested": \{\n\s+"n": 2/);
  const plain = 'use_snake_case and *not emphasis?* [label](https://example.com/raw)';
  assert.ok(render(plain, true, 120).includes(plain));
  const answer = 'Exact answer with **formatting**.\n\n' + '界🙂 long paragraph '.repeat(60) + '\n\nANSWER_TAIL';
  const raw = { jobId: 'job-123', cwd: '/tmp/work', durationMs: 1234, extra: 'RAW_ONLY', job: { status: 'done', role: 'reviewer', kind: 'review', model: 'test/model', reasoning: 'high', answer } };
  context.args.name = 'delegate__delegate_status';
  const prefixed = 'Job job-123: done.\n' + JSON.stringify(raw);
  const full = render(prefixed, true, 100);
  for (const expected of ['done (unverified)', 'role: reviewer', 'kind: review', 'model: test/model', 'reasoning: high', 'jobId: job-123', 'cwd: /tmp/work', 'job duration: 1.2s', 'Exact answer with', 'ANSWER_TAIL', 'Raw result', 'RAW_ONLY', 'Job job-123: done.', '"answer":']) assert.ok(full.includes(expected), `${expected}\n${full}`);
  assert.ok(!render(prefixed).includes('ANSWER_TAIL'));
  assert.ok(render(JSON.stringify(raw), true, 100).includes('Raw result'));
  const nested = { job: { ...raw.job, jobId: raw.jobId, cwd: raw.cwd, durationMs: raw.durationMs } };
  assert.ok(render('Job job-123: done.\n' + JSON.stringify(nested), true, 100).includes('cwd: /tmp/work'));
  context.args.name = 'delegate__delegate_start';
  for (const verb of ['Started', 'Reused']) assert.ok(render(`${verb} job job-123 (done).\n` + JSON.stringify({ ...nested, reused: verb === 'Reused' }), true, 100).includes('Exact answer with'));
  context.args.name = 'delegate__delegate_status';
  assert.ok(!render('Job wrong-id: done.\n' + JSON.stringify(raw), true, 100).includes('Raw result'));
  assert.ok(!render('{"job":{"status":"done"}}', true).includes('Raw result'));
  assert.match(render('Job job-123: done.\n{broken', true), /broken/);
  context.args.name = 'other__delegate_status';
  assert.ok(!render(JSON.stringify(raw), true, 100).includes('Raw result'));
  assert.match(render('partial content', false, 40, { isPartial: true }), /Running/);
  assert.match(render('failure', false, 40, { isError: true }), /Error · 42 ms/);
  const image = render('\u001b[2Jcontrol\u0000\n界🙂'.repeat(30), true, 12, {}, true);
  assert.ok(!image.includes('NEVER_DUMP_BASE64'));
  assert.ok(!image.includes('\u0000'));
  assert.match(image, /image/i);
  for (const width of [1, 2, 5, 12]) render('界🙂'.repeat(80), false, width);
});
